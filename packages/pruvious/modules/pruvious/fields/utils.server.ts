import type { BlockName, Fields, FieldType, GenericDatabase } from '#pruvious/server'
import { blocks } from '#pruvious/server/blocks'
import {
  type ConditionalLogic,
  type Context,
  type DataType,
  type FieldDefinition,
  type GenericField,
} from '@pruvious/orm'
import { isArray, isObject, isString } from '@pruvious/utils'
import { hash } from 'ohash'

export type GenericFieldDefinition = FieldDefinition<
  any,
  any,
  boolean,
  boolean,
  boolean,
  boolean,
  ConditionalLogic | undefined,
  any
>

type BaseSerializableFieldOptions = Required<
  Pick<GenericFieldDefinition, 'nullable' | 'required' | 'immutable' | 'autoGenerated' | 'default' | 'dependencies'>
> &
  Pick<GenericFieldDefinition, 'conditionalLogic'> & {
    /**
     * The registered field type.
     */
    _fieldType: FieldType

    /**
     * The primitive data type of the field.
     * For top-level fields, this determines the database column type.
     *
     * Supported data types:
     *
     * - `bigint`
     * - `boolean`
     * - `junction`
     * - `matrix`
     * - `numeric`
     * - `text`
     */
    _dataType: DataType

    /**
     * Indicates if the field has a populator function.
     */
    _hasPopulator: boolean
  }

export type SerializableFieldOptions<TField extends FieldType> = Readonly<
  BaseSerializableFieldOptions &
    Omit<Fields[TField]['options'], 'populator' | 'structure' | 'subfields'> &
    (Fields[TField]['options'] extends { structure: any }
      ? { structure: { [$key: string]: Record<string, GenericSerializableFieldOptions> } }
      : {}) &
    (Fields[TField]['options'] extends { subfields: any }
      ? { subfields: Record<string, GenericSerializableFieldOptions> }
      : {})
>

export type GenericSerializableFieldOptions = Readonly<BaseSerializableFieldOptions & Record<string, any>>

/**
 * Limits the population of a field to a maximum number of occurrences in a single query.
 * This function is useful to prevent infinite loops when populating fields that reference each other.
 *
 * @throws an error if the population limit is exceeded.
 */
export function limitPopulation(
  value: any,
  { definition, context, path }: { definition: GenericField; context: Context<GenericDatabase>; path: string },
  limit = 32,
) {
  if (!isObject(context.cache['_tmp'])) {
    context.cache['_tmp'] = {}
  }

  if (!(context.cache['_tmp']['_populationLimit'] instanceof Map)) {
    context.cache['_tmp']['_populationLimit'] = new Map()
  }

  const map = context.cache['_tmp']['_populationLimit'] as Map<any, number>
  const entry = hash({ value, definition, path })

  if (!map.has(entry)) {
    map.set(entry, 0)
  }

  map.set(entry, map.get(entry)! + 1)

  if (map.get(entry)! > limit) {
    throw new Error(`Field \`${path}\` has exceeded the maximum population limit (${limit}) in a single query`)
  }
}

/**
 * A function that returns a conditional logic parser for a list of `fields` (including block fields) and their `input` data.
 *
 * Returns an object where:
 *
 * - Keys are field paths (using dot notation for nested fields).
 * - Values are the corresponding conditional logic objects to evaluate (if present).
 */
export function parseConditionalLogic(
  fields: Record<string, Pick<GenericField, 'conditionalLogic' | 'model' | 'options'>>,
  input: Record<string, any>,
): Record<string, ConditionalLogic | undefined> {
  const parsedConditionalLogic: Record<string, ConditionalLogic | undefined> = {}

  for (const [fieldName, field] of Object.entries(fields)) {
    const item = input[fieldName]
    parsedConditionalLogic[fieldName] = field.conditionalLogic

    if (field.model.subfields) {
      if (isObject(item)) {
        for (const [sfp, sfpcl] of Object.entries(parseConditionalLogic(field.model.subfields, item))) {
          parsedConditionalLogic[`${fieldName}.${sfp}`] = sfpcl
        }
      } else if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            for (const [sfp, sfpcl] of Object.entries(parseConditionalLogic(field.model.subfields, arrayItem))) {
              parsedConditionalLogic[`${fieldName}.${index}.${sfp}`] = sfpcl
            }
          }
        }
      }
    } else if (field.model.structure) {
      if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            const subfields = isString(arrayItem.$key) ? field.model.structure[arrayItem.$key] : undefined
            if (subfields) {
              for (const [sfp, sfpcl] of Object.entries(parseConditionalLogic(subfields, arrayItem))) {
                parsedConditionalLogic[`${fieldName}.${index}.${sfp}`] = sfpcl
              }
            }
          }
        }
      }
    } else if (field.options._fieldType === 'blocks') {
      if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            const block = isString(arrayItem.$key) ? blocks[arrayItem.$key as BlockName] : undefined
            if (block) {
              for (const [sfp, sfpcl] of Object.entries(parseConditionalLogic(block.fields, arrayItem))) {
                parsedConditionalLogic[`${fieldName}.${index}.${sfp}`] = sfpcl
              }
            }
          }
        }
      }
    }
  }

  return parsedConditionalLogic
}

/**
 * Parses fields from a list of serializable `fields` and some collection or singleton `data`.
 *
 * Returns an object where:
 *
 * - Keys are field paths (using dot notation for nested fields).
 * - Values are the corresponding field options.
 */
export function parseFields(
  fields: Record<string, GenericField>,
  input: Record<string, any>,
): Record<string, GenericField> {
  const parsedFields: Record<string, GenericField> = {}

  for (const [fieldName, field] of Object.entries(fields)) {
    const item = input[fieldName]
    parsedFields[fieldName] = field

    if (field.model.subfields) {
      if (isObject(item)) {
        for (const [sfp, sfpcl] of Object.entries(parseFields(field.model.subfields, item))) {
          parsedFields[`${fieldName}.${sfp}`] = sfpcl
        }
      } else if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            for (const [sfp, sfpcl] of Object.entries(parseFields(field.model.subfields, arrayItem))) {
              parsedFields[`${fieldName}.${index}.${sfp}`] = sfpcl
            }
          }
        }
      }
    } else if (field.model.structure) {
      if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            const subfields = isString(arrayItem.$key) ? field.model.structure[arrayItem.$key] : undefined
            if (subfields) {
              for (const [sfp, sfpcl] of Object.entries(parseFields(subfields, arrayItem))) {
                parsedFields[`${fieldName}.${index}.${sfp}`] = sfpcl
              }
            }
          }
        }
      }
    } else if (field.options._fieldType === 'blocks') {
      if (isArray(item)) {
        for (const [index, arrayItem] of item.entries()) {
          if (isObject(arrayItem)) {
            const block = isString(arrayItem.$key) ? blocks[arrayItem.$key as BlockName] : undefined
            if (block) {
              for (const [sfp, sfpcl] of Object.entries(parseFields(block.fields, arrayItem))) {
                parsedFields[`${fieldName}.${index}.${sfp}`] = sfpcl
              }
            }
          }
        }
      }
    }
  }

  return parsedFields
}

/**
 * Maximum number of IDs in one batched `where id in (...)` query.
 */
const BATCH_CHUNK_SIZE = 80

interface RecordBatchLoader {
  /**
   * IDs waiting for the next batch, with the callbacks of every caller that asked for them.
   */
  pending: Map<number, { resolve: (value: any) => void; reject: (error: any) => void }[]>

  /**
   * Results of finished batches, keyed by ID (`null` when the record was not found).
   */
  resolved: Map<number, Record<string, any> | null>

  /**
   * Whether a flush is already scheduled for the `pending` IDs.
   */
  scheduled: boolean
}

const scheduleFlush: (callback: () => void) => void =
  typeof setImmediate === 'function' ? (callback) => setImmediate(callback) : (callback) => setTimeout(callback, 0)

/**
 * Loads a single record by `id` for a field populator, batching lookups of the same kind into one query.
 *
 * Populators for single relation fields (`image`, `file`, `record`, `linkedBlocks`) run for every field value of
 * a populate pass. Instead of one `where id = ?` query per value, the IDs requested in the same tick are collected
 * and loaded with one `where id in (...)` query per `collection`, `fields` selection, and `populate` flag.
 *
 * - The loader lives in `context.cache`, so it is shared by the whole populate tree of one top-level query.
 * - The query runs with the same `context.database`, `fields`, `populate`, and `context.cache` as a single lookup,
 *   so collection hooks, guards and nested population apply to each record in the same way.
 * - IDs are only shared while a batch is collecting. A record requested again while its batch is running gets a new
 *   batch, so a record that references itself recurses until `limitPopulation` stops it instead of waiting on itself.
 * - Finished results are reused for the rest of the populate tree, the same as cached `first()` results.
 *
 * Resolves to `null` when the record does not exist or the query fails.
 */
export function loadRecordForPopulator(
  context: Context<GenericDatabase>,
  collection: string,
  fields: string[] | undefined,
  populate: boolean,
  id: number,
): Promise<Record<string, any> | null> {
  const loaders = (context.cache['_batchLoaders'] ??= new Map()) as Map<string, RecordBatchLoader>
  const key = JSON.stringify([collection, fields ?? null, populate])
  let loader = loaders.get(key)

  if (!loader) {
    loader = { pending: new Map(), resolved: new Map(), scheduled: false }
    loaders.set(key, loader)
  }

  if (loader.resolved.has(id)) {
    return Promise.resolve(loader.resolved.get(id)!)
  }

  return new Promise((resolve, reject) => {
    const waiters = loader.pending.get(id)

    if (waiters) {
      waiters.push({ resolve, reject })
    } else {
      loader.pending.set(id, [{ resolve, reject }])
    }

    if (!loader.scheduled) {
      loader.scheduled = true
      scheduleFlush(() => flushRecordBatch(context, collection, fields, populate, loader))
    }
  })
}

async function flushRecordBatch(
  context: Context<GenericDatabase>,
  collection: string,
  fields: string[] | undefined,
  populate: boolean,
  loader: RecordBatchLoader,
) {
  const batch = loader.pending
  loader.pending = new Map()
  loader.scheduled = false

  const ids = [...batch.keys()]
  const selectsId = !fields || fields.includes('id')
  const selectFields = fields ? (selectsId ? fields : [...fields, 'id']) : undefined
  const chunks: number[][] = []

  for (let i = 0; i < ids.length; i += BATCH_CHUNK_SIZE) {
    chunks.push(ids.slice(i, i + BATCH_CHUNK_SIZE))
  }

  await Promise.all(
    chunks.map(async (chunk) => {
      try {
        const queryBuilder = context.database
          .queryBuilder()
          .selectFrom(collection as any)
          .where('id', 'in', chunk)
          .useCache(context.cache)

        if (selectFields) {
          queryBuilder.select(selectFields as any)
        }

        if (populate) {
          queryBuilder.populate()
        }

        const query = await queryBuilder.all()
        const rows = new Map<number, Record<string, any>>()

        if (query.success) {
          for (const row of query.data as Record<string, any>[]) {
            if (selectsId) {
              rows.set(row.id, row)
            } else {
              const { id, ...rest } = row
              rows.set(id, rest)
            }
          }
        }

        for (const id of chunk) {
          const value = query.success ? (rows.get(id) ?? null) : null

          if (query.success) {
            loader.resolved.set(id, value)
          }

          for (const waiter of batch.get(id)!) {
            waiter.resolve(value)
          }
        }
      } catch (error) {
        for (const id of chunk) {
          for (const waiter of batch.get(id)!) {
            waiter.reject(error)
          }
        }
      }
    }),
  )
}
